"""
Lineage Store
-------------
Stores normalized PROV-O provenance records in memory (Python list)
and saves them to a plain Python-readable file (no JSON, no database).

In a production system this would be backed by a graph database like
Neo4j, or a relational database like PostgreSQL. The interface
(store_record, get_record, all_records) would remain the same —
only this file would change.
"""

import os
import pprint

STORE_FILE = os.path.join(os.path.dirname(__file__), "lineage_store_data.py")

# In-memory store (a simple Python list of dicts)
_records: list = []


def store_record(record: dict) -> None:
    """Add a provenance record. Skips duplicates for the same entity."""
    existing = {r["entity"] for r in _records}
    if record["entity"] in existing:
        print(f"  [Store] '{record['entity']}' already stored — skipping.")
        return
    _records.append(record)
    _persist()
    print(f"  [Store] Saved provenance for: '{record['entity']}'")


def get_record(entity_name: str):
    """Find and return the provenance record for a given entity name."""
    for record in _records:
        if record["entity"] == entity_name:
            return record
    return None


def all_records() -> list:
    """Return all stored provenance records."""
    return list(_records)


def clear_store() -> None:
    """Wipe the store clean. Used at the start of each demo run."""
    _records.clear()
    _persist()
    print("[Store] Lineage store cleared.\n")


def _persist() -> None:
    """
    Write all records to a plain Python file.
    This replaces the JSON file — readable by any Python developer.
    """
    with open(STORE_FILE, "w") as f:
        f.write("# Auto-generated by lineage_store.py\n")
        f.write("# Each dict is one PROV-O provenance record\n\n")
        f.write("LINEAGE_RECORDS = ")
        f.write(pprint.pformat(_records, indent=2, width=100))
        f.write("\n")